// Generates supabase/seed.sql and supabase/setup.sql from the curated catalog.
// Run with: npm run build:sql
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const catalog = JSON.parse(fs.readFileSync(path.join(root, "scripts/catalog.json"), "utf8"));
const images = JSON.parse(fs.readFileSync(path.join(root, "scripts/wiki-images.cache.json"), "utf8"));

const q = (value) => "'" + String(value).replace(/'/g, "''") + "'";

const used = new Set();
for (const p of catalog.pairings) {
  used.add(p.a);
  used.add(p.b);
}

const lines = [];
lines.push("-- ---------------------------------------------------------------------------");
lines.push("-- Seed data: characters and curated pairings. Generated by scripts/build-supabase.mjs");
lines.push("-- ---------------------------------------------------------------------------");
lines.push("");
lines.push("truncate table public.assignments, public.game_rounds, public.games, public.players, public.pairings, public.characters restart identity cascade;");
lines.push("");

lines.push("insert into public.characters (key, name, image_url, image_credit, source_url, emoji, is_free_image) values");
const charRows = catalog.characters
  .filter((c) => used.has(c.key))
  .map((c) => {
    const img = images[c.wiki];
    if (!img?.src) throw new Error(`missing image for ${c.key}`);
    const credit = `Wikipedia — ${img.page ?? c.wiki}`;
    const source = `https://en.wikipedia.org/wiki/${encodeURIComponent((img.page ?? c.wiki).replace(/ /g, "_"))}`;
    return `  (${q(c.key)}, ${q(c.name)}, ${q(img.src)}, ${q(credit)}, ${q(source)}, ${q(c.emoji)}, ${img.lic === "free"})`;
  });
lines.push(charRows.join(",\n") + ";");
lines.push("");

lines.push("insert into public.pairings (category, clue, char_a, char_b) values");
const pairingRows = catalog.pairings.map(
  (p) => `  (${q(p.category)}, ${q(p.clue)}, ${q(p.a)}, ${q(p.b)})`,
);
lines.push(pairingRows.join(",\n") + ";");
lines.push("");

const seed = lines.join("\n");
const schema = fs.readFileSync(path.join(root, "supabase", "schema.sql"), "utf8");

fs.writeFileSync(path.join(root, "supabase", "seed.sql"), seed);

const setup = [
  "-- ===========================================================================",
  "--  Mejor en Was — one-shot setup.",
  "--  Paste this entire file into the Supabase SQL editor and run it.",
  "--  (Equivalent to supabase/schema.sql followed by supabase/seed.sql.)",
  "-- ===========================================================================",
  "",
  schema.trim(),
  "",
  seed.trim(),
  "",
].join("\n");
fs.writeFileSync(path.join(root, "supabase", "setup.sql"), setup);

const migrations = path.join(root, "supabase", "migrations");
fs.mkdirSync(migrations, { recursive: true });
for (const f of fs.readdirSync(migrations)) {
  if (f.endsWith(".sql")) fs.unlinkSync(path.join(migrations, f));
}
fs.writeFileSync(path.join(migrations, "20260101000000_init.sql"), schema.trim() + "\n");
fs.writeFileSync(path.join(migrations, "20260101000001_seed.sql"), seed.trim() + "\n");

console.log(
  `wrote supabase/seed.sql (${charRows.length} characters, ${pairingRows.length} pairings), supabase/setup.sql and supabase/migrations/`,
);
